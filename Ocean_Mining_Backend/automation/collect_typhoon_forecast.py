"""Collect observed cyclones and forecast tracks from ECMWF, JMA and NHC."""
import csv
import gzip
import json
import re
import sys
import time
import tempfile
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timedelta, timezone
from pathlib import PurePosixPath
from xml.etree import ElementTree as ET

import eccodes as ec

BASE = "https://data.ecmwf.int"
JMA = "https://www.jma.go.jp/bosai/typhoon/data/targetTc.json"
NHC = "https://www.nhc.noaa.gov/CurrentStorms.json"


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "OceanMining/1.0"})
    for attempt in range(2):
        try:
            with urllib.request.urlopen(req, timeout=18) as response:
                return response.read()
        except urllib.error.HTTPError as exc:
            if exc.code < 500 or attempt:
                raise
        except (OSError, TimeoutError):
            if attempt:
                raise
        time.sleep(1)


def links(path):
    contents = fetch(BASE + path).decode()
    return [s for s in re.findall(r'href="([^"]+)"', contents) if s.startswith(path) and s != path]


def discover():
    for day in sorted((p for p in links("/forecasts/") if re.fullmatch(r"/forecasts/\d{8}/", p)), reverse=True)[:2]:
        for cycle in sorted((p for p in links(day) if re.search(r"/\d{2}z/$", p)), reverse=True):
            files = optional_files(cycle + "ifs/0p25/enfo/")
            tracks = [p for p in files if p.endswith("-enfo-tf.bufr")]
            if tracks:
                return cycle, tracks[-1]
    raise ValueError("未找到集合路径文件")


def optional_files(path):
    try:
        return links(path)
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return []
        raise


def array(message, key):
    try:
        return list(ec.codes_get_array(message, key))
    except ec.KeyValueNotFoundError:
        return []


def value(values, index=0):
    if not values:
        return None
    v = float(values[0] if len(values) == 1 else values[index])
    return v if abs(v) < 1e8 else None


def coord(lat, lon):
    return lat is not None and lon is not None and abs(lat) <= 90 and abs(lon) <= 360


def decode(data, roster, source="ECMWF ENS"):
    initial, horizon, tracks, observed = None, 0, [], {}
    with tempfile.TemporaryFile() as f:
        f.write(data)
        f.seek(0)
        while (message := ec.codes_bufr_new_from_file(getattr(f, "file", f))) is not None:
            try:
                ec.codes_set(message, "unpack", 1)
                stamp = datetime(*(int(ec.codes_get(message, k)) for k in ("year", "month", "day", "hour", "minute")), tzinfo=timezone.utc)
                if initial and stamp != initial:
                    raise ValueError("BUFR批次不一致")
                initial = stamp
                storm = str(ec.codes_get(message, "stormIdentifier")).strip()
                lat = value(array(message, "#1#latitude"))
                lon = value(array(message, "#1#longitude"))
                # Descriptor rank 1 is the observed centre. The model analysis at
                # rank 2 can also exist for a cyclone generated by the model.
                if not coord(lat, lon):
                    continue
                observed[storm] = {"lat": lat, "lon": (lon + 180) % 360 - 180, "time": stamp.isoformat()}
                obs_wind=value(array(message,"#1#windSpeedAt10M"))
                obs_pressure=value(array(message,"#1#pressureReducedToMeanSeaLevel"))
                observed[storm].update(windMs=obs_wind, pressureHpa=obs_pressure/100 if obs_pressure else None)
                members = [int(i) for i in array(message, "ensembleMemberNumber")] if source == "ECMWF ENS" else [0]
                paths = {m: [[]] for m in members if m in roster}
                for rank in range(256):
                    hours = array(message, f"#{rank}#timePeriod") if rank else [0]
                    if not hours:
                        break
                    available = [int(h) for h in hours if abs(h) < 10000]
                    if not available:
                        raise ValueError("BUFR预报时效缺失")
                    hour = available[0]
                    horizon = max(horizon, hour)
                    pos = 2 * rank + 2
                    ys, xs = (array(message, f"#{pos}#{key}") for key in ("latitude", "longitude"))
                    wind = array(message, f"#{rank+1}#windSpeedAt10M")
                    pressure = array(message, f"#{rank+1}#pressureReducedToMeanSeaLevel")
                    for i, member in enumerate(members):
                        if member not in paths:
                            continue
                        y, x = value(ys, i), value(xs, i)
                        if coord(y, x):
                            p = value(pressure, i)
                            paths[member][-1].append({"time": (stamp + timedelta(hours=hour)).isoformat(), "hour": hour, "lat": y, "lon": (x + 180) % 360 - 180, "windMs": value(wind, i), "pressureHpa": p / 100 if p else None})
                        elif paths[member][-1]:
                            paths[member].append([])
                for member, segments in paths.items():
                    for points in segments:
                        if points and source=="ECMWF ENS" and points[0]["hour"]==6:
                            points=[dict(observed[storm],hour=0),*points]
                        if points:
                            tracks.append({"stormId": storm, "member": member, "source": source, "points": points})
            finally:
                ec.codes_release(message)
    if initial is None:
        raise ValueError("BUFR文件为空")
    return {"initialTime": initial.isoformat(), "horizonHours": horizon, "members": sorted(roster), "tracks": tracks, "observedStorms": observed, "source": source, "schemaVersion": 2}


def collect_ensemble():
    cycle, path = discover()
    stamp = PurePosixPath(path).name.split("-")[0]
    roster = set()
    for resolution in ("0p1", "0p25"):
        directory = cycle + f"ifs/{resolution}/enfo/"
        indexes = [p for p in optional_files(directory) if PurePosixPath(p).name in (stamp+"-0h-enfo-ef-sfc.index", stamp+"-0h-enfo-ef.index")]
        if indexes:
            index = fetch(BASE + indexes[0])
            roster = {int(r["number"]) for r in map(json.loads, index.decode().splitlines()) if r.get("type") == "pf" and r.get("number") is not None}
            if roster:
                break
    if not roster:
        raise ValueError("集合成员索引不可用")
    result = decode(fetch(BASE + path), roster)
    result["sourceUrl"] = BASE + path
    result["horizonHours"] = int(re.search(r"-(\d+)h-enfo-tf", path)[1])
    result["complete"] = roster == set(range(1, 51)) and result["horizonHours"] >= 120 and set(result["observedStorms"]) == {t["stormId"] for t in result["tracks"]}
    try:
        deterministic = []
        for resolution in ("0p25","0p1"):
            for kind in ("oper","scda"):
                deterministic.extend(p for p in optional_files(cycle+f"ifs/{resolution}/{kind}/") if p.endswith("-tf.bufr"))
            if deterministic:
                break
        result["comparisonTracks"] = decode(fetch(BASE + deterministic[0]), {0}, "ECMWF IFS")["tracks"] if deterministic else []
    except Exception as exc:
        result["comparisonTracks"] = []
        result["deterministicError"] = str(exc)
    return result


def nhc_tracks(storm):
    ident = str(storm.get("id", "")).lower()
    if not re.fullmatch(r"(al|ep|cp)\d{6}", ident):
        return []
    data = gzip.decompress(fetch(f"https://ftp.nhc.noaa.gov/atcf/aid_public/a{ident}.dat.gz")).decode()
    cycles = {}
    for row in csv.reader(data.splitlines(), skipinitialspace=True):
        if len(row) < 10 or row[4].strip() != "OFCL":
            continue
        hour = int(row[5])
        if not 0 <= hour <= 120:
            continue
        lat, lon = (int(s[:-1]) / 10 * (-1 if s[-1] in "SW" else 1) for s in map(str.strip, row[6:8]))
        stamp = datetime.strptime(row[2].strip(), "%Y%m%d%H").replace(tzinfo=timezone.utc)
        cycles.setdefault(stamp, {})[hour] = {"time": (stamp+timedelta(hours=hour)).isoformat(), "lat": lat, "lon": lon, "windMs": int(row[8] or 0)*0.514444 or None, "pressureHpa": int(row[9] or 0) or None}
    if not cycles:
        return []
    stamp = max(cycles)
    sid = ident[2:4] + {"al":"L", "ep":"E", "cp":"C"}[ident[:2]]
    return [{"stormId":sid,"name":storm.get("name"),"source":"NHC","initialTime":stamp.isoformat(),"points":[p for _,p in sorted(cycles[stamp].items())]}]


def jma_tracks():
    # JMA regular/extra bulletins publish VPTW tropical cyclone track XML.
    feed = ET.fromstring(fetch("https://www.data.jma.go.jp/developer/xml/feed/extra_l.xml"))
    tracks = {}
    for entry in feed.findall("{*}entry"):
        url = entry.findtext("{*}id", "")
        if not re.fullmatch(r"https://www\.data\.jma\.go\.jp/(?:developer/xml/data|bosai/forecast/data)/[\w.-]*VPTW[\w.-]*\.xml", url):
            continue
        root = ET.fromstring(fetch(url))
        sid = root.findtext(".//{*}EventID", "")
        if not sid or sid in tracks:
            continue
        issued = root.findtext(".//{*}ReportDateTime", "")
        if not issued or datetime.fromisoformat(issued) < datetime.now(timezone.utc)-timedelta(hours=18):
            continue
        pts = []
        for info in root.findall(".//{*}MeteorologicalInfo"):
            ts = info.findtext("{*}DateTime")
            center = info.find(".//{*}CenterPart")
            if center is None or not ts:
                continue
            for node in center.iter():
                if node.tag.rsplit("}",1)[-1] not in ("Coordinate","BasePoint"):
                    continue
                match = re.match(r"([+-]\d+(?:\.\d+)?)([+-]\d+(?:\.\d+)?)/", (node.text or "").strip())
                if match:
                    pts.append({"time":ts,"lat":float(match[1]),"lon":float(match[2])})
                    break
        if pts:
            tracks[sid] = {"stormId":sid,"source":"JMA","initialTime":issued,"points":sorted(pts,key=lambda p:p["time"])}
        if len(tracks) >= 8:
            break
    return list(tracks.values())


def activity(source, url):
    report = {"source":source, "url":url, "fetchedAt":datetime.now(timezone.utc).isoformat(), "tracks":[]}
    try:
        data = json.loads(fetch(url))
        storms = data["activeStorms"] if source == "NHC" else data
        if not isinstance(storms, list):
            raise ValueError("活动列表格式异常")
        report.update(ok=True, data=data)
        if storms:
            try:
                report["tracks"] = [track for storm in storms for track in nhc_tracks(storm)] if source == "NHC" else jma_tracks()
            except Exception as exc:
                report["trackError"] = str(exc)
    except Exception as exc:
        report.update(ok=False, error=str(exc))
    return report


def main():
    with ThreadPoolExecutor(max_workers=3) as pool:
        ensemble = pool.submit(collect_ensemble)
        feeds = [pool.submit(activity, "JMA", JMA), pool.submit(activity, "NHC", NHC)]
        result = ensemble.result()
        result["activity"] = [task.result() for task in feeds]
    print(json.dumps(result, ensure_ascii=False, separators=(",", ":")))


if __name__ == "__main__":
    main()
