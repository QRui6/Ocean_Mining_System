/**
 * 获取承包者对应的颜色
 * @param {string} contractor - 承包者名称
 * @returns {string} 十六进制颜色值
 */
export function getContractorColor(contractor) {
    if (!contractor) return '#808080';
    
    // 1. 直接精确匹配
    if (CONTRACTOR_COLORS[contractor]) {
        return CONTRACTOR_COLORS[contractor];
    }
    
    // 2. 模糊匹配 - 检查是否包含关键词
    const contractorLower = contractor.toLowerCase();
    
    // 特殊处理 APEI
    if (contractorLower.includes('apei') || contractorLower.includes('环境特别受关注区')) {
        return '#A9A9A9';
    }
    
    // 特殊处理保留区
    if (contractorLower.includes('reserved') || contractorLower.includes('保留区')) {
        return '#FFFF00';
    }
    
    // 遍历所有映射进行模糊匹配
    for (const [key, color] of Object.entries(CONTRACTOR_COLORS)) {
        const keyLower = key.toLowerCase();
        
        // 双向包含匹配
        if (contractorLower.includes(keyLower) || keyLower.includes(contractorLower)) {
            return color;
        }
        
        // 提取缩写进行匹配（如 COMRA, BGR, GSR 等）
        const acronymMatch = key.match(/\(([A-Z]+)[,\)]/);
        if (acronymMatch && contractorLower.includes(acronymMatch[1].toLowerCase())) {
            return color;
        }
    }
    
    // 3. 默认颜色（未匹配到的显示为灰色）
    console.warn(`⚠️ 未找到承包者颜色映射: ${contractor}`);
    return '#808080';
}
